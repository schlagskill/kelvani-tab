export const locale = () => (language === "en" ? "en-GB" : "de-DE");
export function translate(value, lang = language) {
  if (lang !== "en" || typeof value !== "string") return value;
  const normalized = value.trim().replace(/\s+/g, " ");
  if (Object.hasOwn(EN, normalized))
    return value.replace(value.trim(), EN[normalized]);
  const handle = normalized.match(
    /^(⠿ )?(.+?) (verschieben|ausblenden|Größe ändern)$/,
  );
  if (handle)
    return `${handle[1] || ""}${translate(handle[2], "en")} ${{ verschieben: "move", ausblenden: "hide", "Größe ändern": "resize" }[handle[3]]}`;
  if (normalized.startsWith("⠿ "))
    return "⠿ " + translate(normalized.slice(2), "en");
  const today = normalized.match(/^Heute, (\d+)\.$/);
  if (today) return `Today, ${today[1]}.`;
  for (const prefix of [
    "Import fehlgeschlagen: ",
    "Das Layout konnte nicht geändert werden. ",
  ]) {
    if (normalized.startsWith(prefix))
      return (
        (prefix === "Import fehlgeschlagen: "
          ? "Import failed: "
          : translate(prefix.trim(), "en") + " ") +
        translate(normalized.slice(prefix.length), "en")
      );
  }
  const retained = " Vorhandene Daten behalten ihren angezeigten Zeitstempel.";
  if (normalized.endsWith(retained))
    return (
      translate(normalized.slice(0, -retained.length), "en") +
      " " +
      translate(retained.trim(), "en")
    );
  return value;
}
// UI-only text nodes: never translate user-entered links, tasks, notes or event names.
export function enableTranslations() {
  const originals = new WeakMap(),
    attributes = new WeakMap();
  const excluded =
    "script,style,textarea,.shortcut-title,.shortcut-icon,#tasks label span,#weather-results,#countdown-caption,#greeting,#date,.calendar-title,#world-time,#header-motivation,#panel-inspiration blockquote,#photo-credit";
  const observer = new MutationObserver(apply);
  function observe() {
    const body = document.body;
    if (!body || body.nodeType !== 1) return;
    observer.observe(body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["aria-label", "title", "placeholder"],
    });
  }
  function apply() {
    if (!document.body) return;
    observer.disconnect();
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
    );
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (node.parentElement?.closest(excluded)) continue;
      const prior = originals.get(node),
        raw =
          prior && node.nodeValue === prior.translated
            ? prior.raw
            : node.nodeValue;
      const translated = translate(raw);
      originals.set(node, { raw, translated });
      if (node.nodeValue !== translated) node.nodeValue = translated;
    }
    for (const node of document.querySelectorAll(
      "[aria-label],[placeholder],[title]",
    )) {
      const saved = attributes.get(node) || {};
      for (const key of ["aria-label", "placeholder", "title"]) {
        if (!node.hasAttribute(key)) continue;
        const value = node.getAttribute(key),
          prior = saved[key],
          raw = prior && value === prior.translated ? prior.raw : value;
        const translated = translate(raw);
        saved[key] = { raw, translated };
        if (value !== translated) node.setAttribute(key, translated);
      }
      attributes.set(node, saved);
    }
    observe();
  }
  const listener = () => apply();
  document.addEventListener("kelvani-language", listener);
  apply();
  return () => {
    observer.disconnect();
    document.removeEventListener("kelvani-language", listener);
  };
}
export function setLanguage(next) {
  const changed = language !== next;
  language = next === "en" ? "en" : "de";
  if (typeof document !== "undefined") {
    document.documentElement.lang = language;
    document.title =
      language === "en" ? "New tab · KelvaniTab" : "Neuer Tab · KelvaniTab";
    if (changed) document.dispatchEvent(new Event("kelvani-language"));
  }
}
